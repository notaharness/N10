#!/usr/bin/env node
// Concatenates every content/docs/**/*.mdx file into a bundled string
// constant, for `/llms-full.txt` to serve with zero file I/O at request
// time. A route handler that reads source files via `node:fs` at request
// time works during `next build` (real Node, real filesystem) but not
// once deployed: the Workers runtime has no access to files outside what
// OpenNext explicitly bundles, and re-executes `force-static` route
// handlers on a cache miss rather than only ever serving the build-time
// output. Baking the content into a JS string literal at build time
// avoids depending on either.
import {
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
  mkdirSync,
} from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = fileURLToPath(new URL('..', import.meta.url));
const contentDir = join(projectRoot, 'content/docs');
const outFile = join(projectRoot, 'src/generated/llms-full-content.ts');

function walk(dir) {
  const entries = readdirSync(dir).sort();
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else if (entry.endsWith('.mdx')) files.push(full);
  }
  return files;
}

const sections = walk(contentDir).map((file) => {
  const raw = readFileSync(file, 'utf-8');
  const content = raw.replace(/^---\n[\s\S]*?\n---\n/, '').trim();
  const slug = relative(contentDir, file)
    .replace(/\.mdx$/, '')
    .replace(/\/index$/, '');
  const url = slug === 'index' ? '/docs' : `/docs/${slug}`;
  return `# ${url}\n\n${content}`;
});

mkdirSync(join(projectRoot, 'src/generated'), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/generate-llms-full.mjs — do not edit by hand.\n` +
    `export const llmsFullContent = ${JSON.stringify(
      sections.join('\n\n---\n\n')
    )};\n`
);

console.log(`Wrote ${outFile}`);
